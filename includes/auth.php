if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

/**
 * Check if the user is authenticated
 */
function is_logged_in() {
    return isset($_SESSION['user_id']) && !empty($_SESSION['user_id']);
}

/**
 * Require login or redirect to login.php
 */
function require_login($redirectUrl = '') {
    if (!is_logged_in()) {
        $path = $redirectUrl ?: $_SERVER['REQUEST_URI'];
        // Determine relative path to login.php
        $base = (strpos($_SERVER['PHP_SELF'], '/admin/') !== false) ? '../login.php' : 'login.php';
        header("Location: " . $base . "?redirect=" . urlencode($path));
        exit;
    }
}

/**
 * Get current logged in user details
 */
function current_user() {
    if (!is_logged_in()) return null;
    return [
        'id'        => $_SESSION['user_id'] ?? 0,
        'username'  => $_SESSION['username'] ?? 'User',
        'full_name' => $_SESSION['full_name'] ?? 'Supervisor',
        'role'      => $_SESSION['role'] ?? 'Admin'
    ];
}

/**
 * Set a flash message
 */
function set_flash($type, $message) {
    $_SESSION['flash_message'] = [
        'type'    => $type, // 'success', 'error', 'warning', 'info'
        'message' => $message
    ];
}

/**
 * Get and clear flash message
 */
function get_flash() {
    if (isset($_SESSION['flash_message'])) {
        $flash = $_SESSION['flash_message'];
        unset($_SESSION['flash_message']);
        return $flash;
    }
    return null;
}

/**
 * Escape string for HTML output
 */
function e($str) {
    return htmlspecialchars((string)($str ?? ''), ENT_QUOTES, 'UTF-8');
}

/**
 * Format currency amount with Indian Rupee symbol
 */
function format_currency($amount, $decimals = 2) {
    $num = (float)$amount;
    return '₹ ' . number_format($num, $decimals, '.', ',');
}

/**
 * Format date for clean display
 */
function format_date($dateStr, $format = 'd M Y') {
    if (empty($dateStr) || $dateStr === '0000-00-00') return '-';
    $time = strtotime($dateStr);
    return $time ? date($format, $time) : $dateStr;
}

/**
 * Fetch all active sites for dropdown selectors
 */
function get_active_sites($conn) {
    $res = mysqli_query($conn, "SELECT id, site_name, location, status FROM sites WHERE status = 'Active' ORDER BY site_name ASC");
    return mysqli_fetch_all($res, MYSQLI_ASSOC);
}

/**
 * Fetch all sites regardless of status
 */
function get_all_sites($conn) {
    $res = mysqli_query($conn, "SELECT id, site_name, location, status FROM sites ORDER BY site_name ASC");
    return mysqli_fetch_all($res, MYSQLI_ASSOC);
}

/**
 * Fetch all active workers for dropdown selectors
 */
function get_active_workers($conn) {
    $res = mysqli_query($conn, "SELECT id, name, worker_type, daily_wage, phone FROM workers WHERE status = 'Active' ORDER BY name ASC");
    return mysqli_fetch_all($res, MYSQLI_ASSOC);
}

